import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import {
  validatePipelineSchema
} from "../src/contracts.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const checkOnly = process.argv.includes("--check");
const schema = JSON.parse(
  await readFile(resolve(root, "config/pipeline-schema.json"), "utf8")
);
const review = JSON.parse(
  await readFile(resolve(root, "config/review-sheet.json"), "utf8")
);

const schemaErrors = validatePipelineSchema(schema);
if (schemaErrors.length > 0) {
  throw new Error(`Invalid pipeline schema:\n- ${schemaErrors.join("\n- ")}`);
}
if (review?.schema_version !== 2) {
  throw new Error("review-sheet schema_version must be 2");
}
if (
  JSON.stringify(review.all_record_columns) !== JSON.stringify(schema.fields)
) {
  throw new Error("review-sheet all_record_columns must exactly match schema fields");
}

const setup = {
  timezone: review.timezone,
  sheets: review.sheets,
  recordFields: schema.fields,
  editableColumns: review.editable_columns,
  actionValidation: review.action_validation,
  outcomeValidation: review.outcome_validation,
  forbiddenLegacySheets: review.fresh_start.forbidden_legacy_sheets,
  maximumRows: 2000
};

const generated = String.raw`// Generated by scripts/build-sheet-setup.mjs. Do not edit directly.
// This provisions a fresh workbook only. It never reads another workbook or imports old rows.
const JOB_PIPELINE_SETUP = ${JSON.stringify(setup, null, 2)};

function setupFreshJobPipeline() {
  const workbook = SpreadsheetApp.getActive();
  workbook.setSpreadsheetTimeZone(JOB_PIPELINE_SETUP.timezone);
  const lock = LockService.getDocumentLock();
  lock.waitLock(30000);
  try {
    const expected = [
      JOB_PIPELINE_SETUP.sheets.review_queue.name,
      JOB_PIPELINE_SETUP.sheets.applied_jobs.name,
      JOB_PIPELINE_SETUP.sheets.archive.name,
      JOB_PIPELINE_SETUP.sheets.system.name
    ];

    // Create the intended tabs before removing an empty default Sheet1.
    expected.forEach((name) => {
      if (!workbook.getSheetByName(name)) workbook.insertSheet(name);
    });

    workbook.getSheets().forEach((sheet) => {
      if (expected.includes(sheet.getName())) return;
      if (sheet.getLastRow() > 1 || sheet.getLastColumn() > 1 ||
          String(sheet.getRange(1, 1).getValue() || '').trim() !== '') {
        throw new Error(
          'Fresh setup refused to delete non-empty unexpected sheet: ' +
          sanitizeSetupDiagnostic_(sheet.getName())
        );
      }
      workbook.deleteSheet(sheet);
    });

    configureRecordSheet_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.review_queue.name),
      JOB_PIPELINE_SETUP.sheets.review_queue.visible_columns
    );
    configureRecordSheet_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.applied_jobs.name),
      JOB_PIPELINE_SETUP.sheets.applied_jobs.visible_columns
    );
    configureRecordSheet_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.archive.name),
      JOB_PIPELINE_SETUP.sheets.archive.visible_columns
    );
    configureSystemSheet_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.system.name)
    );
    applyReviewActionValidation_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.review_queue.name)
    );
    applyOutcomeValidation_(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.applied_jobs.name)
    );
    workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.system.name).hideSheet();
    workbook.setActiveSheet(
      workbook.getSheetByName(JOB_PIPELINE_SETUP.sheets.review_queue.name)
    );
  } finally {
    lock.releaseLock();
  }
}

function configureRecordSheet_(sheet, visibleColumns) {
  ensureSheetCapacity_(
    sheet,
    JOB_PIPELINE_SETUP.maximumRows,
    JOB_PIPELINE_SETUP.recordFields.length
  );
  reconcileHeaders_(sheet, JOB_PIPELINE_SETUP.recordFields);
  sheet.setFrozenRows(1);
  sheet.getRange(1, 1, 1, JOB_PIPELINE_SETUP.recordFields.length)
    .setFontWeight('bold')
    .setBackground('#d9ead3');
  sheet.getRange(1, 1, Math.max(sheet.getMaxRows(), 2), JOB_PIPELINE_SETUP.recordFields.length)
    .setVerticalAlignment('top');

  const editable = new Set(JOB_PIPELINE_SETUP.editableColumns[sheet.getName()] || []);
  sheet.getProtections(SpreadsheetApp.ProtectionType.RANGE).forEach((protection) => {
    if (String(protection.getDescription() || '').startsWith('Job Pipeline generated:')) {
      protection.remove();
    }
  });

  JOB_PIPELINE_SETUP.recordFields.forEach((field, offset) => {
    const column = offset + 1;
    if (visibleColumns.includes(field)) {
      sheet.showColumns(column);
      sheet.setColumnWidth(
        column,
        ['generated_message', 'decision_reason', 'required_input', 'notes'].includes(field)
          ? 360
          : ['canonical_url', 'job_title'].includes(field) ? 240 : 140
      );
      if (['generated_message', 'decision_reason', 'required_input', 'notes'].includes(field)) {
        sheet.getRange(2, column, Math.max(sheet.getMaxRows() - 1, 1), 1)
          .setWrap(true);
      }
    } else {
      sheet.hideColumns(column);
    }
    if (!editable.has(field)) {
      const protection = sheet
        .getRange(1, column, Math.max(sheet.getMaxRows(), 2), 1)
        .protect()
        .setDescription('Job Pipeline generated:' + sheet.getName() + ':' + field);
      protection.setWarningOnly(true);
    }
  });

  if (!sheet.getFilter()) {
    sheet.getRange(1, 1, Math.max(sheet.getLastRow(), 1), JOB_PIPELINE_SETUP.recordFields.length)
      .createFilter();
  }
}

function configureSystemSheet_(sheet) {
  ensureSheetCapacity_(
    sheet,
    JOB_PIPELINE_SETUP.maximumRows,
    JOB_PIPELINE_SETUP.sheets.system.fields.length
  );
  reconcileHeaders_(sheet, JOB_PIPELINE_SETUP.sheets.system.fields);
  sheet.setFrozenRows(1);
  sheet.getRange(1, 1, 1, JOB_PIPELINE_SETUP.sheets.system.fields.length)
    .setFontWeight('bold')
    .setBackground('#eeeeee');
  sheet.getProtections(SpreadsheetApp.ProtectionType.SHEET).forEach((protection) => {
    if (protection.getDescription() === 'Job Pipeline generated:_System') {
      protection.remove();
    }
  });
  sheet.protect()
    .setDescription('Job Pipeline generated:_System')
    .setWarningOnly(true);
}

function ensureSheetCapacity_(sheet, minimumRows, minimumColumns) {
  if (sheet.getMaxRows() < minimumRows) {
    sheet.insertRowsAfter(
      sheet.getMaxRows(),
      minimumRows - sheet.getMaxRows()
    );
  }
  if (sheet.getMaxColumns() < minimumColumns) {
    sheet.insertColumnsAfter(
      sheet.getMaxColumns(),
      minimumColumns - sheet.getMaxColumns()
    );
  }
}

function reconcileHeaders_(sheet, headers) {
  const lastRow = sheet.getLastRow();
  const current = sheet
    .getRange(1, 1, 1, Math.max(sheet.getLastColumn(), headers.length))
    .getValues()[0]
    .map((value) => String(value || '').trim());
  const hasHeader = current.some(Boolean);
  if (hasHeader) {
    const actual = current.slice(0, headers.length);
    const extra = current.slice(headers.length).filter(Boolean);
    if (JSON.stringify(actual) !== JSON.stringify(headers) || extra.length > 0) {
      throw new Error(
        'Fresh setup found conflicting headers in sheet: ' +
        sanitizeSetupDiagnostic_(sheet.getName())
      );
    }
  } else {
    sheet.getRange(1, 1, 1, headers.length).setValues([headers]);
  }
  if (lastRow > 1 && !hasHeader) {
    throw new Error('Fresh setup found data without headers');
  }
}

function applyReviewActionValidation_(sheet) {
  const statusColumn = JOB_PIPELINE_SETUP.recordFields.indexOf('pipeline_status') + 1;
  const actionColumn = JOB_PIPELINE_SETUP.recordFields.indexOf('user_action') + 1;
  const status = columnLetter_(statusColumn);
  const action = columnLetter_(actionColumn);
  const firstRow = 2;
  const formula =
    '=OR(' + action + firstRow + '="",' +
    'AND(' + status + firstRow + '="ready_to_apply",OR(' +
      action + firstRow + '="I Applied",' + action + firstRow + '="Skip")),' +
    'AND(' + status + firstRow + '="review_needed",OR(' +
      action + firstRow + '="Approve",' + action + firstRow + '="Deny")))';
  const validation = SpreadsheetApp.newDataValidation()
    .requireFormulaSatisfied(formula)
    .setAllowInvalid(false)
    .setHelpText('ready_to_apply: I Applied or Skip; review_needed: Approve or Deny')
    .build();
  sheet.getRange(
    firstRow,
    actionColumn,
    JOB_PIPELINE_SETUP.maximumRows - 1,
    1
  ).setDataValidation(validation);
}

function applyOutcomeValidation_(sheet) {
  const outcomeColumn = JOB_PIPELINE_SETUP.recordFields.indexOf('outcome') + 1;
  const validation = SpreadsheetApp.newDataValidation()
    .requireValueInList(JOB_PIPELINE_SETUP.outcomeValidation, true)
    .setAllowInvalid(false)
    .build();
  sheet.getRange(
    2,
    outcomeColumn,
    JOB_PIPELINE_SETUP.maximumRows - 1,
    1
  ).setDataValidation(validation);
}

function sanitizeSetupDiagnostic_(value) {
  return String(value || '')
    .replace(/https?:\/\/\S+/gi, '[url]')
    .replace(/[\r\n\t]+/g, ' ')
    .slice(0, 120);
}

function columnLetter_(column) {
  let value = column;
  let result = '';
  while (value > 0) {
    const remainder = (value - 1) % 26;
    result = String.fromCharCode(65 + remainder) + result;
    value = Math.floor((value - 1) / 26);
  }
  return result;
}
`;

const target = resolve(root, "google-apps-script/SheetSetup.gs");
if (checkOnly) {
  const current = await readFile(target, "utf8");
  if (current !== generated) {
    throw new Error(
      "google-apps-script/SheetSetup.gs is out of date; run npm run build:sheet-setup"
    );
  }
  console.log("Google Sheets setup artifact is up to date.");
} else {
  await mkdir(resolve(root, "google-apps-script"), { recursive: true });
  await writeFile(target, generated);
  console.log("Google Sheets setup artifact rebuilt.");
}
