function inspectArchivedLegacyMessageTargets_(sheet) {
  const summary = {
    sheet: sheet.getName(),
    records: {
      archived: [],
      missing: [],
      conflicting: []
    }
  };
  const headers = sheet
    .getRange(1, 1, 1, sheet.getLastColumn())
    .getDisplayValues()[0];
  const idColumn = headers.indexOf('canonical_job_id');
  const statusColumn = headers.indexOf('pipeline_status');
  if (idColumn < 0 || statusColumn < 0) {
    summary.records.conflicting.push({
      row_number: 1,
      canonical_job_id: '',
      reason: 'required_header_missing'
    });
    return summary;
  }

  const rowCount = Math.max(sheet.getLastRow() - 1, 0);
  const rows =
    rowCount > 0
      ? sheet.getRange(2, 1, rowCount, sheet.getLastColumn()).getValues()
      : [];
  LEGACY_MESSAGE_QUARANTINE_IDS.forEach((identity) => {
    const matches = [];
    rows.forEach((row, index) => {
      if (String(row[idColumn] || '').trim() === identity) {
        matches.push({
          row_number: index + 2,
          pipeline_status: String(row[statusColumn] || '').trim()
        });
      }
    });
    if (matches.length === 0) {
      summary.records.missing.push({
        canonical_job_id: identity
      });
      return;
    }
    if (matches.length > 1) {
      summary.records.conflicting.push({
        row_number: matches[0].row_number,
        canonical_job_id: identity,
        reason: 'duplicate_archive_records'
      });
      return;
    }
    if (matches[0].pipeline_status !== 'archived') {
      summary.records.conflicting.push({
        row_number: matches[0].row_number,
        canonical_job_id: identity,
        reason: 'unexpected_archive_status'
      });
      return;
    }
    summary.records.archived.push({
      row_number: matches[0].row_number,
      canonical_job_id: identity
    });
  });
  return summary;
}

function repairLegacyApplyPointsInputs_(sheet) {
  const summary = {
    sheet: sheet.getName(),
    counts: {
      cleared: 0,
      blank: 0,
      valid: 0,
      conflicting: 0
    },
    records: {
      cleared: [],
      conflicting: []
    }
  };
  const headers = sheet
    .getRange(1, 1, 1, sheet.getLastColumn())
    .getDisplayValues()[0];
  const column = headers.indexOf('apply_points_input') + 1;
  if (column < 1) {
    summary.counts.conflicting += 1;
    summary.records.conflicting.push({
      row_number: 1,
      reason: 'required_header_missing'
    });
    return summary;
  }

  const rowCount = Math.max(sheet.getLastRow() - 1, 0);
  if (rowCount === 0) return summary;
  const values = sheet.getRange(2, column, rowCount, 1).getValues();
  const candidates = [];
  values.forEach((row, index) => {
    const value = row[0];
    if (value === '' || value === null || value === undefined) {
      summary.counts.blank += 1;
      return;
    }
    if (value === 0 || String(value).trim() === '0') {
      candidates.push(index + 2);
      return;
    }
    const numeric = Number(value);
    if (
      Number.isInteger(numeric) &&
      numeric >= JOB_PIPELINE_SETUP.reviewInputRules.applyPoints.minimum &&
      numeric <= JOB_PIPELINE_SETUP.reviewInputRules.applyPoints.maximum
    ) {
      summary.counts.valid += 1;
      return;
    }
    summary.counts.conflicting += 1;
    summary.records.conflicting.push({
      row_number: index + 2,
      value: String(value).slice(0, 64),
      reason: 'unsupported_legacy_value'
    });
  });
  if (summary.counts.conflicting > 0) return summary;

  candidates.forEach((rowNumber) => {
    const range = sheet.getRange(rowNumber, column);
    const current = range.getValue();
    if (!(current === 0 || String(current).trim() === '0')) {
      summary.counts.conflicting += 1;
      summary.records.conflicting.push({
        row_number: rowNumber,
        value: String(current).slice(0, 64),
        reason: 'target_changed_during_cleanup'
      });
      return;
    }
    range.setValue('');
    summary.counts.cleared += 1;
    if (summary.records.cleared.length < 20) {
      summary.records.cleared.push({
        row_number: rowNumber,
        reason: 'legacy_zero_sentinel'
      });
    }
  });
  return summary;
}

function repairAndFormatVersionColumns_(sheet) {
  const summary = {
    sheet: sheet.getName(),
    formatted: [],
    repaired: [],
    unmapped: []
  };
  const headers = sheet
    .getRange(1, 1, 1, sheet.getLastColumn())
    .getDisplayValues()[0];
  const headerIndex = Object.fromEntries(
    headers.map((header, index) => [header, index])
  );
  const rowCount = Math.max(sheet.getLastRow() - 1, 0);
  const dataRowCount = Math.max(sheet.getMaxRows() - 1, 1);
  const rawRows =
    rowCount > 0
      ? sheet
          .getRange(2, 1, rowCount, sheet.getLastColumn())
          .getValues()
      : [];
  const displayRows =
    rowCount > 0
      ? sheet
          .getRange(2, 1, rowCount, sheet.getLastColumn())
          .getDisplayValues()
      : [];
  const identityFields = [
    'canonical_job_id',
    'analytics_row_id',
    'report_id',
    'recommendation_id',
    'run_id'
  ];
  const identityForRow = (row, displayRow) => {
    for (const field of identityFields) {
      const column = headerIndex[field];
      if (column === undefined) continue;
      const identity = String(row[column] || displayRow[column] || '').trim();
      if (identity) return identity;
    }
    return '';
  };
  const repairs = [];

  JOB_PIPELINE_SETUP.versionFields.forEach((field) => {
    const column = headerIndex[field];
    if (column === undefined) return;
    summary.formatted.push(field);

    rawRows.forEach((row, rowIndex) => {
      const result = classifyVersionCell({
        field,
        value: row[column],
        displayValue: displayRows[rowIndex][column],
        identity: identityForRow(row, displayRows[rowIndex])
      });
      if (result.status === 'repair') {
        repairs.push({
          row: rowIndex + 2,
          column: column + 1,
          field,
          identity: identityForRow(row, displayRows[rowIndex]),
          value: result.value,
          raw_type: result.raw_type
        });
      } else if (result.status === 'unmapped') {
        summary.unmapped.push({
          row_number: rowIndex + 2,
          field,
          identity: identityForRow(row, displayRows[rowIndex]),
          raw_type: result.raw_type,
          display_value: String(displayRows[rowIndex][column] || '').slice(0, 64)
        });
      }
    });

    sheet
      .getRange(2, column + 1, dataRowCount, 1)
      .setNumberFormat('@');
  });

  repairs.forEach((repair) => {
    sheet.getRange(repair.row, repair.column).setValue(repair.value);
    summary.repaired.push({
      row_number: repair.row,
      field: repair.field,
      identity: repair.identity,
      raw_type: repair.raw_type,
      value: repair.value
    });
  });
  return summary;
}

function repairOrphanedProcessingClaims_(sheet) {
  const summary = {
    sheet: sheet.getName(),
    counts: {
      cleared: 0,
      preserved_active: 0,
      skipped: 0,
      conflicting: 0
    },
    records: {
      cleared: [],
      preserved_active: [],
      skipped: [],
      conflicting: []
    }
  };
  const headers = sheet
    .getRange(1, 1, 1, sheet.getLastColumn())
    .getDisplayValues()[0];
  const headerIndex = Object.fromEntries(
    headers.map((header, index) => [header, index])
  );
  const requiredFields = [
    'canonical_job_id',
    'pipeline_status',
    'processing_stage',
    'processing_token',
    'processing_started_at'
  ];
  if (requiredFields.some((field) => headerIndex[field] === undefined)) {
    summary.counts.conflicting += 1;
    summary.records.conflicting.push({
      row_number: 1,
      canonical_job_id: '',
      reason: 'required_header_missing'
    });
    return summary;
  }

  const rowCount = Math.max(sheet.getLastRow() - 1, 0);
  if (rowCount === 0) return summary;
  const rows = sheet
    .getRange(2, 1, rowCount, sheet.getLastColumn())
    .getValues();
  const recordFromRow = (row) =>
    Object.fromEntries(
      requiredFields.map((field) => [field, row[headerIndex[field]]])
    );
  const recordResult = (bucket, rowNumber, record, reason) => {
    summary.counts[bucket] += 1;
    if (summary.records[bucket].length < 20) {
      summary.records[bucket].push({
        row_number: rowNumber,
        canonical_job_id: String(record.canonical_job_id || '').slice(0, 128),
        reason
      });
    }
  };

  rows.forEach((row, index) => {
    const rowNumber = index + 2;
    const record = recordFromRow(row);
    const classification = classifyOrphanedProcessingClaim({
      record,
      nowMs: Date.now(),
      leaseMs: JOB_PIPELINE_SETUP.maximumClaimLeaseMs
    });
    if (classification.status !== 'clear') {
      recordResult(
        classification.status,
        rowNumber,
        record,
        classification.reason
      );
      return;
    }

    const currentRow = sheet
      .getRange(rowNumber, 1, 1, sheet.getLastColumn())
      .getValues()[0];
    const currentRecord = recordFromRow(currentRow);
    const rechecked = classifyOrphanedProcessingClaim({
      record: currentRecord,
      nowMs: Date.now(),
      leaseMs: JOB_PIPELINE_SETUP.maximumClaimLeaseMs
    });
    if (rechecked.status !== 'clear') {
      recordResult(
        'conflicting',
        rowNumber,
        currentRecord,
        'target_changed_during_cleanup'
      );
      return;
    }

    sheet
      .getRange(rowNumber, headerIndex.processing_token + 1)
      .setValue('');
    recordResult(
      'cleared',
      rowNumber,
      currentRecord,
      classification.reason
    );
  });
  return summary;
}

