function setupJobPipelineSheets() {
  const spreadsheet = SpreadsheetApp.getActiveSpreadsheet();
  const active = ensureSheet_(spreadsheet, JOB_PIPELINE_SETUP.activeSheet, JOB_PIPELINE_SETUP.recordFields);
  const archive = ensureSheet_(spreadsheet, JOB_PIPELINE_SETUP.archiveSheet, JOB_PIPELINE_SETUP.recordFields);
  const claims = ensureSheet_(spreadsheet, JOB_PIPELINE_SETUP.claimsSheet, JOB_PIPELINE_SETUP.claimFields);
  const dashboard = ensureSheet_(spreadsheet, JOB_PIPELINE_SETUP.dashboardSheet, JOB_PIPELINE_SETUP.dashboardFields);
  const analytics = ensureSheet_(
    spreadsheet,
    JOB_PIPELINE_SETUP.analyticsSheet,
    JOB_PIPELINE_SETUP.analyticsFields
  );
  const analyticsReports = ensureSheet_(
    spreadsheet,
    JOB_PIPELINE_SETUP.analyticsReportsSheet,
    JOB_PIPELINE_SETUP.analyticsReportFields
  );
  const recommendations = ensureSheet_(
    spreadsheet,
    JOB_PIPELINE_SETUP.recommendationsSheet,
    JOB_PIPELINE_SETUP.recommendationFields
  );
  const recommendationReports = ensureSheet_(
    spreadsheet,
    JOB_PIPELINE_SETUP.recommendationReportsSheet,
    JOB_PIPELINE_SETUP.recommendationReportFields
  );

  migrateLegacyCreatedAt_(active);
  migrateLegacyCreatedAt_(archive);
  migrateLegacyIdentityAndState_(active);
  migrateLegacyIdentityAndState_(archive);
  orderReviewColumns_(active);
  orderReviewColumns_(archive);
  applyReviewLayout_(active);
  applyReviewLayout_(archive);
  formatInternalSheet_(claims);
  formatInternalSheet_(dashboard);
  formatInternalSheet_(analytics);
  formatInternalSheet_(analyticsReports);
  formatInternalSheet_(recommendations);
  formatInternalSheet_(recommendationReports);

  SpreadsheetApp.flush();
  const duplicateActiveIds = duplicateCanonicalIds_(active);
  const duplicateArchiveIds = duplicateCanonicalIds_(archive);
  if (duplicateActiveIds.length || duplicateArchiveIds.length) {
    throw new Error(
      'Canonical identity collisions require manual reconciliation before workflow activation. ' +
      'Sheet1: ' + duplicateActiveIds.join(', ') +
      '; Archive: ' + duplicateArchiveIds.join(', ')
    );
  }
  return {
    activeRows: active.getLastRow(),
    archiveRows: archive.getLastRow(),
    activeColumns: active.getLastColumn(),
    archiveColumns: archive.getLastColumn()
  };
}

function duplicateCanonicalIds_(sheet) {
  if (sheet.getLastRow() < 2) return [];
  const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
  const idColumn = headers.indexOf('canonical_job_id') + 1;
  if (idColumn < 1) return [];
  const values = sheet
    .getRange(2, idColumn, sheet.getLastRow() - 1, 1)
    .getDisplayValues()
    .flat()
    .filter(Boolean);
  const seen = new Set();
  const duplicates = new Set();
  values.forEach((value) => {
    if (seen.has(value)) duplicates.add(value);
    seen.add(value);
  });
  return [...duplicates];
}

function ensureSheet_(spreadsheet, name, requiredHeaders) {
  const sheet = spreadsheet.getSheetByName(name) || spreadsheet.insertSheet(name);
  const existingWidth = Math.max(sheet.getLastColumn(), 1);
  const existing = sheet.getRange(1, 1, 1, existingWidth).getDisplayValues()[0];
  const headers = existing.every((value) => !value) ? [] : existing;
  const missing = requiredHeaders.filter((header) => !headers.includes(header));
  const merged = headers.concat(missing);
  if (merged.length > 0) {
    sheet.getRange(1, 1, 1, merged.length).setValues([merged]);
  }
  sheet.setFrozenRows(1);
  return sheet;
}

function migrateLegacyCreatedAt_(sheet) {
  const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
  const legacyIndex = headers.indexOf('created_at ');
  const canonicalIndex = headers.indexOf('created_at');
  if (legacyIndex < 0 || canonicalIndex < 0 || sheet.getLastRow() < 2) return;

  const rowCount = sheet.getLastRow() - 1;
  const legacy = sheet.getRange(2, legacyIndex + 1, rowCount, 1).getValues();
  const canonicalRange = sheet.getRange(2, canonicalIndex + 1, rowCount, 1);
  const canonical = canonicalRange.getValues();
  const merged = canonical.map((row, index) => [row[0] || legacy[index][0] || '']);
  canonicalRange.setValues(merged);
}

function migrateLegacyIdentityAndState_(sheet) {
  if (sheet.getLastRow() < 2) return;
  const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
  const headerIndex = Object.fromEntries(headers.map((header, index) => [header, index]));
  const rows = sheet
    .getRange(2, 1, sheet.getLastRow() - 1, sheet.getLastColumn())
    .getValues();
  const targets = [
    'source',
    'source_job_id',
    'canonical_job_id',
    'canonical_url',
    'pipeline_status',
    'application_decision',
    'first_reviewed_at',
    'apply_points_used',
    'application_message_strategy',
    'archived_from_status',
    'profile_version',
    'message_profile_version',
    'outcome_events',
    'state_guard'
  ];
  const output = Object.fromEntries(targets.map((target) => [target, []]));
  const value = (row, header) =>
    headerIndex[header] === undefined ? '' : row[headerIndex[header]];

  rows.forEach((row) => {
    const hasJob = [
      'canonical_job_id',
      'canonical_url',
      'job_url',
      'source_job_id',
      'job_title'
    ].some((header) => String(value(row, header) || '').trim());
    const current = Object.fromEntries(targets.map((target) => [target, value(row, target)]));
    if (!hasJob) {
      targets.forEach((target) => output[target].push([current[target]]));
      return;
    }

    const source = String(current.source || 'onlinejobs.ph').trim().toLowerCase();
    const canonicalUrl =
      String(current.canonical_url || '').trim() ||
      normalizeLegacyUrl_(value(row, 'job_url'));
    const sourceJobId =
      String(current.source_job_id || '').trim() ||
      (canonicalUrl.match(/\/jobseekers\/job\/[^/]*?(\d+)$/i) || [])[1] ||
      '';
    const canonicalJobId =
      String(current.canonical_job_id || '').trim() ||
      (sourceJobId
        ? source + ':' + sourceJobId
        : canonicalUrl
          ? source + ':url:' + fnv32_(canonicalUrl)
          : '');
    const legacyStatus = String(value(row, 'status') || '').trim().toLowerCase();
    const mappedLegacyStatus =
      JOB_PIPELINE_SETUP.legacyStatusMapping[legacyStatus] || legacyStatus || 'discovered';
    let pipelineStatus = String(current.pipeline_status || '').trim() || mappedLegacyStatus;
    let archivedFromStatus = String(current.archived_from_status || '').trim();
    if (
      sheet.getName() === JOB_PIPELINE_SETUP.archiveSheet &&
      !String(current.pipeline_status || '').trim()
    ) {
      archivedFromStatus = archivedFromStatus || mappedLegacyStatus;
      pipelineStatus = 'archived';
    }
    const applicationDecision =
      String(current.application_decision || '').trim() ||
      (archivedFromStatus === 'applied' || pipelineStatus === 'applied'
        ? 'applied'
        : archivedFromStatus === 'skipped' || pipelineStatus === 'skipped'
          ? 'skipped'
          : '');
    const outcome = String(value(row, 'outcome') || '').trim();
    const firstReviewedAt = String(current.first_reviewed_at || '').trim();
    const applyPointsUsed = String(current.apply_points_used || '').trim();
    const applicationMessageStrategy =
      String(current.application_message_strategy || '').trim();
    const outcomeEvents = String(current.outcome_events || '').trim();
    const generatedMessage = String(value(row, 'generated_message') || '');
    const profileVersion = String(current.profile_version || '').trim() || 'legacy/unknown';
    const messageProfileVersion =
      String(current.message_profile_version || '').trim() ||
      (generatedMessage ? 'legacy/unknown' : '');
    const stateGuard = canonicalJobId
      ? stateGuard_(
          canonicalJobId,
          pipelineStatus,
          applicationDecision,
          firstReviewedAt,
          applyPointsUsed,
          applicationMessageStrategy,
          outcome,
          outcomeEvents
        )
      : '';
    const migrated = {
      source,
      source_job_id: sourceJobId,
      canonical_job_id: canonicalJobId,
      canonical_url: canonicalUrl,
      pipeline_status: pipelineStatus,
      application_decision: applicationDecision,
      first_reviewed_at: firstReviewedAt,
      apply_points_used: applyPointsUsed,
      application_message_strategy: applicationMessageStrategy,
      archived_from_status: archivedFromStatus,
      profile_version: profileVersion,
      message_profile_version: messageProfileVersion,
      outcome_events: outcomeEvents,
      state_guard: stateGuard
    };
    targets.forEach((target) => output[target].push([migrated[target]]));
  });

  targets.forEach((target) => {
    const column = headerIndex[target];
    if (column !== undefined) {
      sheet.getRange(2, column + 1, rows.length, 1).setValues(output[target]);
    }
  });
}

function normalizeLegacyUrl_(value) {
  let url = String(value || '').trim();
  if (!url) return '';
  if (url.startsWith('/')) url = 'https://onlinejobs.ph' + url;
  url = url
    .replace(/^http:\/\//i, 'https://')
    .replace(/^https:\/\/www\.onlinejobs\.ph/i, 'https://onlinejobs.ph')
    .split(/[?#]/)[0]
    .replace(/\/+$/, '');
  return /^https:\/\/onlinejobs\.ph\/jobseekers\/job\//i.test(url) ? url : '';
}

function stateGuard_(
  canonicalJobId,
  pipelineStatus,
  applicationDecision,
  firstReviewedAt,
  applyPointsUsed,
  applicationMessageStrategy,
  outcome,
  outcomeEvents
) {
  return (
    canonicalJobId +
    '|' +
    fnv32_(
      [
        canonicalJobId,
        pipelineStatus,
        applicationDecision,
        firstReviewedAt,
        applyPointsUsed,
        applicationMessageStrategy,
        outcome,
        outcomeEvents || '[]'
      ].join(
        String.fromCharCode(31)
      )
    )
  );
}

function fnv32_(value) {
  let hash = 2166136261;
  String(value).split('').forEach((character) => {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  });
  return (hash >>> 0).toString(16).padStart(8, '0');
}

function orderReviewColumns_(sheet) {
  const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
  let destination = 1;
  JOB_PIPELINE_SETUP.reviewColumns.forEach((header) => {
    const currentIndex = headers.indexOf(header);
    if (currentIndex < 0) return;
    if (currentIndex + 1 !== destination) {
      sheet.moveColumns(
        sheet.getRange(1, currentIndex + 1, sheet.getMaxRows(), 1),
        destination
      );
      const [moved] = headers.splice(currentIndex, 1);
      headers.splice(destination - 1, 0, moved);
    }
    destination += 1;
  });
}

function applyReviewLayout_(sheet) {
  const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
  const actionColumn = headers.indexOf('manual_action') + 1;
  if (actionColumn > 0) {
    const validation = SpreadsheetApp.newDataValidation()
      .requireValueInList(JOB_PIPELINE_SETUP.manualActions, true)
      .setAllowInvalid(false)
      .setHelpText('Choose a supported Job Pipeline action. The reviewer workflow validates the state transition.')
      .build();
    sheet.getRange(2, actionColumn, Math.max(sheet.getMaxRows() - 1, 1), 1).setDataValidation(validation);
  }

  const applyPointsColumn = headers.indexOf('apply_points_input') + 1;
  if (applyPointsColumn > 0) {
    const rule = JOB_PIPELINE_SETUP.reviewInputRules.applyPoints;
    const column = columnLetter_(applyPointsColumn);
    const validation = SpreadsheetApp.newDataValidation()
      .requireFormulaSatisfied(
        '=OR($' + column + '2="",AND(ISNUMBER($' + column +
        '2),$' + column + '2=INT($' + column + '2),$' + column +
        '2>=' + rule.minimum + ',$' + column + '2<=' + rule.maximum + '))'
      )
      .setAllowInvalid(false)
      .setHelpText(
        'Optional actual Apply Points. Enter a whole number from ' +
        rule.minimum + ' to ' + rule.maximum + ', or leave blank when unknown.'
      )
      .build();
    sheet
      .getRange(2, applyPointsColumn, Math.max(sheet.getMaxRows() - 1, 1), 1)
      .setDataValidation(validation);
  }

  const strategyColumn =
    headers.indexOf('application_message_strategy_input') + 1;
  if (strategyColumn > 0) {
    const pattern = String(
      JOB_PIPELINE_SETUP.reviewInputRules.messageStrategy.pattern
    ).replace(/"/g, '""');
    const column = columnLetter_(strategyColumn);
    const validation = SpreadsheetApp.newDataValidation()
      .requireFormulaSatisfied(
        '=OR($' + column + '2="",REGEXMATCH(TO_TEXT($' +
        column + '2),"' + pattern + '"))'
      )
      .setAllowInvalid(false)
      .setHelpText(
        'Optional versioned strategy identifier, for example instruction-aware/v1.'
      )
      .build();
    sheet
      .getRange(2, strategyColumn, Math.max(sheet.getMaxRows() - 1, 1), 1)
      .setDataValidation(validation);
  }

  const statusColumn = headers.indexOf('pipeline_status') + 1;
  if (statusColumn > 0) {
    const range = sheet.getRange(2, statusColumn, Math.max(sheet.getMaxRows() - 1, 1), 1);
    const rules = [
      conditionalRule_(range, '=$' + columnLetter_(statusColumn) + '2="ready"', '#d9ead3'),
      conditionalRule_(range, '=$' + columnLetter_(statusColumn) + '2="recommended"', '#cfe2f3'),
      conditionalRule_(range, '=$' + columnLetter_(statusColumn) + '2="review_required"', '#fff2cc'),
      conditionalRule_(range, '=$' + columnLetter_(statusColumn) + '2="retryable_error"', '#f4cccc'),
      conditionalRule_(range, '=$' + columnLetter_(statusColumn) + '2="unavailable"', '#d9d9d9')
    ];
    const unrelatedRules = sheet.getConditionalFormatRules().filter((rule) =>
      rule.getRanges().every(
        (ruleRange) =>
          ruleRange.getSheet().getSheetId() !== sheet.getSheetId() ||
          statusColumn < ruleRange.getColumn() ||
          statusColumn > ruleRange.getLastColumn()
      )
    );
    sheet.setConditionalFormatRules(unrelatedRules.concat(rules));
  }

  const messageColumn = headers.indexOf('generated_message') + 1;
  if (messageColumn > 0) {
    sheet.setColumnWidth(messageColumn, 420);
    sheet.getRange(2, messageColumn, Math.max(sheet.getMaxRows() - 1, 1), 1).setWrap(true);
  }
  const titleColumn = headers.indexOf('job_title') + 1;
  if (titleColumn > 0) sheet.setColumnWidth(titleColumn, 260);
  const urlColumn = headers.indexOf('canonical_url') + 1;
  if (urlColumn > 0) sheet.setColumnWidth(urlColumn, 260);
  [
    'match_reasons',
    'requirement_gaps',
    'requirement_gap_details',
    'ranking_factors',
    'ranking_missing_signals',
    'application_instructions',
    'screening_questions',
    'selected_proof_refs',
    'application_warnings',
    'notes'
  ].forEach((header) => {
    const column = headers.indexOf(header) + 1;
    if (column > 0) {
      sheet.setColumnWidth(column, 280);
      sheet.getRange(2, column, Math.max(sheet.getMaxRows() - 1, 1), 1).setWrap(true);
    }
  });
  JOB_PIPELINE_SETUP.hiddenColumns.forEach((header) => {
    const column = headers.indexOf(header) + 1;
    if (column > 0) sheet.hideColumns(column);
  });
  sheet.setFrozenColumns(Math.min(3, sheet.getLastColumn()));
  sheet.getRange(1, 1, 1, sheet.getLastColumn()).setFontWeight('bold').setBackground('#1f4e78').setFontColor('#ffffff');

  removeGeneratedProtections_(sheet);
  headers.forEach((header, index) => {
    if (!JOB_PIPELINE_SETUP.editableColumns.includes(header)) {
      const protection = sheet
        .getRange(2, index + 1, Math.max(sheet.getMaxRows() - 1, 1), 1)
        .protect()
        .setDescription('Job Pipeline generated field: ' + header);
      protection.setWarningOnly(true);
    }
  });
}

function formatInternalSheet_(sheet) {
  sheet.getRange(1, 1, 1, sheet.getLastColumn()).setFontWeight('bold').setBackground('#666666').setFontColor('#ffffff');
  sheet.autoResizeColumns(1, sheet.getLastColumn());
}

function removeGeneratedProtections_(sheet) {
  sheet.getProtections(SpreadsheetApp.ProtectionType.RANGE).forEach((protection) => {
    if ((protection.getDescription() || '').startsWith('Job Pipeline generated field:')) {
      protection.remove();
    }
  });
}

function conditionalRule_(range, formula, color) {
  return SpreadsheetApp.newConditionalFormatRule()
    .whenFormulaSatisfied(formula)
    .setBackground(color)
    .setRanges([range])
    .build();
}

function sortPriorityQueue() {
  const sheet = SpreadsheetApp.getActiveSpreadsheet().getSheetByName(JOB_PIPELINE_SETUP.activeSheet);
  if (!sheet || sheet.getLastRow() < 3) return;
  const lock = LockService.getDocumentLock();
  if (!lock.tryLock(5000)) throw new Error('Priority queue is busy; retry the sort.');
  try {
    const headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getDisplayValues()[0];
    const index = Object.fromEntries(headers.map((header, position) => [header, position]));
    for (const required of [
      'pipeline_status',
      'opportunity_score',
      'match_score',
      'ranking_confidence',
      'posted_at',
      'created_at',
      'canonical_job_id'
    ]) {
      if (index[required] === undefined) throw new Error(required + ' column is required');
    }
    const range = sheet.getRange(2, 1, sheet.getLastRow() - 1, sheet.getLastColumn());
    const rows = range.getValues();
    const statusPriority = {
      ready: 4,
      recommended: 3,
      review_required: 2,
      retryable_error: 1
    };
    const confidencePriority = { high: 3, medium: 2, low: 1 };
    const rankingValue = (row) => {
      const opportunity = row[index.opportunity_score];
      if (String(opportunity ?? '').trim() !== '' && Number.isFinite(Number(opportunity))) {
        return Number(opportunity);
      }
      const legacy = row[index.match_score];
      return String(legacy ?? '').trim() !== '' && Number.isFinite(Number(legacy))
        ? Number(legacy)
        : 0;
    };
    const timestamp = (value) => {
      const parsed = value instanceof Date ? value.getTime() : Date.parse(String(value || ''));
      return Number.isFinite(parsed) ? parsed : Number.NEGATIVE_INFINITY;
    };
    rows.sort((left, right) => {
      const status =
        (statusPriority[String(right[index.pipeline_status])] || 0) -
        (statusPriority[String(left[index.pipeline_status])] || 0);
      if (status !== 0) return status;
      const score = rankingValue(right) - rankingValue(left);
      if (score !== 0) return score;
      const confidence =
        (confidencePriority[String(right[index.ranking_confidence])] || 0) -
        (confidencePriority[String(left[index.ranking_confidence])] || 0);
      if (confidence !== 0) return confidence;
      const rightPosted = timestamp(right[index.posted_at]);
      const leftPosted = timestamp(left[index.posted_at]);
      if (rightPosted !== leftPosted) return rightPosted > leftPosted ? 1 : -1;
      const rightCreated = timestamp(right[index.created_at]);
      const leftCreated = timestamp(left[index.created_at]);
      if (rightCreated !== leftCreated) return rightCreated > leftCreated ? 1 : -1;
      return String(left[index.canonical_job_id] || '').localeCompare(
        String(right[index.canonical_job_id] || '')
      );
    });
    range.setValues(rows);
  } finally {
    lock.releaseLock();
  }
}

function columnLetter_(column) {
  let value = column;
  let result = '';
  while (value > 0) {
    const remainder = (value - 1) % 26;
    result = String.fromCharCode(65 + remainder) + result;
    value = Math.floor((value - 1) / 26);
  }
  return result;
}
